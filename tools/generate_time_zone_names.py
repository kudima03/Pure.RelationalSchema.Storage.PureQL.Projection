#!/usr/bin/env python3
"""Writes TimeZoneNames.cs: the time zone names a `zone` may hold, from the
specification's tools/time_zones.txt.

    python3 generate_time_zone_names.py <time_zones.txt> <TimeZoneNames.cs>
"""
import re
import sys


def main(source, target):
    with open(source, encoding="utf-8") as lines:
        header = lines.readline()
        names = [
            line.strip()
            for line in lines
            if line.strip() and not line.startswith("#")
        ]
    release = None
    with open(source, encoding="utf-8") as lines:
        for line in lines:
            found = re.search(r"release ([0-9]{4}[a-z]+)", line)
            if found:
                release = found.group(1)
                break
    if not header.startswith("#") or release is None:
        raise SystemExit("the list does not say which release it is from")
    if len(set(names)) != len(names):
        raise SystemExit("a name is listed twice")
    for name in names:
        if not re.fullmatch(r"[A-Za-z0-9_+/-]+", name):
            raise SystemExit(f"unexpected name {name!r}")
    out = [
        "using System.Collections.Frozen;",
        "",
        "namespace Pure.RelationalSchema.Storage.PureQL.Projection;",
        "",
        "// The time zone names a zone may hold: the names of the specification's",
        f"// tools/time_zones.txt, {len(names)} names from release {release} of the IANA time",
        "// zone database. The list has no name for UTC, which is the absence of a",
        "// zone. Generated by tools/generate_time_zone_names.py: never edit it by",
        "// hand.",
        "internal static class TimeZoneNames",
        "{",
        "    public static FrozenSet<string> All { get; } =",
        "        FrozenSet.ToFrozenSet(",
        "            [",
    ]
    out += [f'                "{name}",' for name in names]
    out += [
        "            ],",
        "            StringComparer.Ordinal",
        "        );",
        "}",
        "",
    ]
    with open(target, "w", encoding="utf-8", newline="\n") as file:
        file.write("\n".join(out))
    print(f"{len(names)} names from release {release}")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
